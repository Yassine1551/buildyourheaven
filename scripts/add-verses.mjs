const uniqueNewItems = newItems.filter(item => !existingTitles.has(item.title));
console.log(`Adding ${uniqueNewItems.length} new items`);

const allItems = [...items, ...uniqueNewItems];
console.log(`Total: ${allItems.length}`);

// Sort by Mushaf order
allItems.sort((a, b) => {
  const surahA = extractSurahNum(a.title);
  const surahB = extractSurahNum(b.title);
  if (surahA !== surahB) return surahA - surahB;
  return extractAyahNum(a.title) - extractAyahNum(b.title);
});

// Ensure Al-Fatiha is first
const fatihaIdx = allItems.findIndex(i => i.title === 'سورة الفاتحة');
if (fatihaIdx > 0) {
  const [fatiha] = allItems.splice(fatihaIdx, 1);
  allItems.unshift(fatiha);
}

// Generate the new file content
let output = `export interface VerseItem {
  id: string;
  title: string;
  verses: string;
  virtue: string;
  order: number;
}

export const versesData: VerseItem[] = [
`;

allItems.forEach((item, index) => {
  const id = index + 1;
  const order = index + 1;
  output += `{
    id: '${id}',
    title: '${item.title}',
    verses: '${item.verses}',
    virtue: '${item.virtue}',
    order: ${order}
  },\n`;
});

output += '];\n';

fs.writeFileSync(sourceFile, output, 'utf8');
console.log(`Written ${allItems.length} items`);
