// Extract surah number from title
function extractSurahNum(title) {
  // Match surah name in parentheses or direct name
  const parenMatch = title.match(/\(([^)]+)\s+\d/);
  if (parenMatch) {
    const name = parenMatch[1].trim();
    if (surahMap[name]) return surahMap[name];
  }
  // Direct surah name (for complete surahs)
  for (const [name, num] of Object.entries(surahMap)) {
    if (title.includes(`سورة ${name}`)) return num;
  }
  if (title === 'سورة الفاتحة') return 1;
  if (title.includes('سورة ')) {
    const suraName = title.replace('سورة ', '');
    if (surahMap[suraName]) return surahMap[suraName];
  }
  return 999; // Unknown - put at end
}

// Extract starting ayah number
function extractAyahNum(title) {
  const match = title.match(/(\d+)\s*[-–]/);
  if (match) return parseInt(match[1], 10);
  return 0;
}

// Determine if item should be removed (surah 78-112 except 113-114)
function shouldRemove(title) {
  const surahNum = extractSurahNum(title);
  return surahNum >= 78 && surahNum <= 112;
}

